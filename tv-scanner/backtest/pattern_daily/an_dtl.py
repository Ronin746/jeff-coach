import pandas as pd, numpy as np
b=pd.concat([pd.read_pickle('brk_0.pkl'),pd.read_pickle('brk_1.pkl')],ignore_index=True)
b['yr']=pd.to_datetime(b.day).dt.year; b['volok']=(b.vol>=1.5)|(b.conf>=1.5)
print('rotture',len(b), 'titoli',b.t.nunique())
def row(lab,m):
    x=b[m]
    per=[x[(x.yr>=a)&(x.yr<=z)].r20.mean() for a,z in ((2017,2019),(2020,2021),(2022,2023),(2024,2026))]
    print(f"{lab:40s} n={len(x):5d} r10 {x.r10.mean():+.2f} r20 {x.r20.mean():+.2f} r40 {x.r40.mean():+.2f} +2/-1 {x.h2v1.mean():.2f} +4/-2 {x.h4v2.mean():.2f} fallite10 {x.fail10.mean():.0%} | r20 per periodo "+' '.join(f'{p:+.2f}' for p in per))
T=pd.Series(True,index=b.index)
row('tutte le rotture (RS>=70 al campione)',T)
for k in (2,3,4,5): row(f'tocchi == {k}' if k<5 else 'tocchi >= 5', (b.touches==k) if k<5 else (b.touches>=5))
row('tocchi >= 3',b.touches>=3)
row('volume >=1,5 (o conferma)',b.volok); row('senza volume',~b.volok)
row('tocchi>=3 e volume',(b.touches>=3)&b.volok)
for lo,hi in ((70,80),(80,90),(90,100)): row(f'RS {lo}-{hi}',(b.rs>=lo)&(b.rs<hi))
for lo,hi in ((15,25),(25,40),(40,100)): row(f'discesa {lo}-{hi}%',(b['drop']>=lo)&(b['drop']<hi))
for lo,hi in ((20,40),(40,80),(80,300)): row(f'durata {lo}-{hi} sedute',(b.span>=lo)&(b.span<hi))
for lo,hi in ((0.03,0.06),(0.06,0.12),(0.12,9)): row(f'pendenza {lo}-{hi} ATR/seduta',(b.slope.abs()>=lo)&(b.slope.abs()<hi))
for lo,hi in ((0,0.5),(0.5,1.5),(1.5,99)): row(f'close sopra la linea {lo}-{hi} ATR',(b.above_atr>=lo)&(b.above_atr<hi))
for lo,hi in ((-99,0),(0,3),(3,99)): row(f'estensione SMA50 {lo}-{hi} ATR',(b.ext>=lo)&(b.ext<hi))
for lo,hi in ((-100,-25),(-25,-10),(-10,1)): row(f'dal massimo 52 sett. {lo}..{hi}%',(b.off52>=lo)&(b.off52<hi))
row('above200 si',b.above200==True); row('above200 no',b.above200==False)
for lo,hi in ((-99,0),(0,20),(20,50),(50,999)): row(f'ret63 {lo}..{hi}%',(b.ret63>=lo)&(b.ret63<hi))
q=(b.touches>=3)
row('3+ tocchi, vol, sopra linea <1,5 ATR',q&b.volok&(b.above_atr<1.5))
row('3+ tocchi, durata>=40',q&(b.span>=40))
row('3+ tocchi, discesa>=25',q&(b['drop']>=25))
print('---- combinazioni')
q=(b.touches>=3)
row('NUOVA: 3+ tocchi, discesa>=25, durata>=40',q&(b['drop']>=25)&(b.span>=40))
row('NUOVA + volume',q&(b['drop']>=25)&(b.span>=40)&b.volok)
row('NUOVA senza volume',q&(b['drop']>=25)&(b.span>=40)&~b.volok)
row('VECCHIA (2+ tocchi, 15%, 20 sedute)',T)
row('scartate dalla nuova',~(q&(b['drop']>=25)&(b.span>=40)))
row('3+ tocchi, discesa>=20, durata>=30',q&(b['drop']>=20)&(b.span>=30))
x=b[q&(b['drop']>=25)&(b.span>=40)]; print('al mese',round(len(x)/108,1),'(campionamento RS>=70 sopra SMA200)')
